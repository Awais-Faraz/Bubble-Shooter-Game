"""Logic test: builds all 100 levels, checks fairness with a bot. (No pygame needed)"""
import os, sys, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from game.levels import build_level, simulate, compute_par
from game.settings import TOTAL_LEVELS

def main(write_pars=False):
    sigs, bad, pars = set(), [], {}
    t0 = time.time()
    for n in range(1, TOTAL_LEVELS + 1):
        lv = build_level(n)
        assert lv.cells, "level %d empty" % n
        colored = [c for c in lv.cells if c[3] == "normal"]
        assert len(colored) >= 8, "level %d too small" % n
        assert any(c[0] == 0 for c in lv.cells), "level %d has no ceiling anchor" % n
        sig = tuple(lv.cells)
        assert sig not in sigs, "level %d duplicates another level" % n
        sigs.add(sig)
        pars[n] = compute_par(lv.cells)
        lv_par = pars[n][0]
        limit = lv.shots
        results = [simulate(lv.cells, s) for s in (11, 12, 13, 14, 15, 16)]
        sloppy = [simulate(lv.cells, s, sloppy=0.25) for s in (21, 22, 23, 24)]
        ok = limit is None or (max(results) <= limit)
        ok_sloppy = limit is None or (max(sloppy) <= limit)
        if not ok or not ok_sloppy:
            bad.append((n, limit, results, sloppy))
        if n % 10 == 0 or not ok:
            print("L%3d %-24s bubbles=%3d colors=%d par=%2d limit=%s bot=%s sloppy=%s" % (
                n, lv.name, len(lv.cells), len(lv.colors), lv_par, limit, results, sloppy))
    print("levels checked:", TOTAL_LEVELS, "unique layouts:", len(sigs), "time %.1fs" % (time.time() - t0))
    print("PROBLEMS:", bad if bad else "none")
    if write_pars:
        with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "game", "level_pars.py"), "w") as f:
            f.write('"""Pre-computed par shot counts (generated by tests/test_levels.py)."""\nPARS = %r\n' % pars)
    return 0 if not bad else 1

if __name__ == "__main__":
    sys.exit(main(write_pars="--write-pars" in sys.argv))
